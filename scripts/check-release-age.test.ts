const NOW = new Date('2026-06-15T12:00:00Z');
const daysAgo = (d: number) => new Date(NOW.getTime() - d * 86_400_000).toISOString();
const REG = 'https://registry.npmjs.org/';

function npmLock(packages: Record<string, object>) {
  return JSON.stringify({
    name: 'fixture-app',
    lockfileVersion: 3,
    requires: true,
    packages: { '': { name: 'fixture-app', version: '1.0.0' }, ...packages },
  });
}

const tgz = (name: string, version: string) => `${REG}${name}/-/${name.split('/').pop()}-${version}.tgz`;
const pkg = (name: string, version: string) => ({ version, resolved: tgz(name, version), integrity: 'sha512-x' });

const CARGO_HEADER = '# This file is automatically @generated by Cargo.\nversion = 3\n';
function cargoLock(pkgs: { name: string; version: string; source?: string }[]) {
  return (
    CARGO_HEADER +
    pkgs
      .map(
        (p) =>
          `\n[[package]]\nname = "${p.name}"\nversion = "${p.version}"\n` +
          (p.source === undefined ? '' : `source = "${p.source}"\nchecksum = "abc"\n`) +
          'dependencies = [\n "other-crate",\n]\n',
      )
      .join('')
  );
}
const CRATES = 'registry+https://github.com/rust-lang/crates.io-index';

describe('parseNpmLock', () => {
  it('reads name from the key, or from "name" for an alias, and classifies sources', () => {
    const entries = parseNpmLock(
      npmLock({
        'node_modules/alpha-lib': pkg('alpha-lib', '1.2.3'),
        'node_modules/@fixture/beta': pkg('@fixture/beta', '2.0.0'),
        'node_modules/alpha-lib/node_modules/gamma-util': pkg('gamma-util', '0.4.1'),
        'node_modules/aliased': { name: 'delta-real', ...pkg('delta-real', '3.1.0') },
        'node_modules/from-git': { version: '1.0.0', resolved: 'git+ssh://git@example.com/x/y.git#abc' },
        'node_modules/from-file': { version: '1.0.0', resolved: 'file:../local-thing' },
        'node_modules/linked': { resolved: 'packages/linked', link: true },
        'node_modules/alpha-lib/node_modules/bundled-dep': { version: '1.0.0', inBundle: true },
        'packages/linked': { name: 'linked', version: '0.0.1' },
      }),
    );
    const byName = Object.fromEntries(entries.map((e) => [e.name, e]));
    expect(byName['alpha-lib']).toMatchObject({ version: '1.2.3', registry: true });
    expect(byName['@fixture/beta']).toMatchObject({ version: '2.0.0', registry: true });
    expect(byName['gamma-util']).toMatchObject({ version: '0.4.1', registry: true });
    expect(byName['delta-real']).toMatchObject({ version: '3.1.0', registry: true });
    expect(byName['aliased']).toBeUndefined();
    expect(byName['from-git']).toMatchObject({ registry: false, source: expect.stringContaining('git+ssh') });
    expect(byName['from-file']).toMatchObject({ registry: false, source: 'file:../local-thing' });
    expect(byName['linked']).toMatchObject({ registry: false, source: expect.stringContaining('link') });
    expect(byName['bundled-dep']).toMatchObject({ registry: false, source: expect.stringContaining('bundled') });
    expect(entries.some((e) => e.name === 'fixture-app')).toBe(false);
  });

  it('keeps one entry per name@version when it is installed at several paths', () => {
    const entries = parseNpmLock(
      npmLock({
        'node_modules/a/node_modules/dup': pkg('dup', '1.0.0'),
        'node_modules/b/node_modules/dup': pkg('dup', '1.0.0'),
        'node_modules/dup': pkg('dup', '2.0.0'),
      }),
    );
    expect(entries.filter((e) => e.name === 'dup').map((e) => e.version).sort()).toEqual(['1.0.0', '2.0.0']);
  });

  it('treats an empty file as no packages and refuses a lockfile without "packages"', () => {
    expect(parseNpmLock('')).toEqual([]);
    expect(() => parseNpmLock(JSON.stringify({ lockfileVersion: 1, dependencies: {} }))).toThrow(/lockfileVersion/);
  });
});

describe('parseCargoLock', () => {
  it('reads [[package]] tables and only treats crates.io as a registry', () => {
    const entries = parseCargoLock(
      cargoLock([
        { name: 'fixture-app', version: '0.1.0' },
        { name: 'alpha-crate', version: '1.0.200', source: CRATES },
        { name: 'beta-crate', version: '0.3.0', source: 'git+https://example.com/beta?rev=abc#abc' },
      ]) + '\n[metadata]\n"checksum x" = "y"\n',
    );
    expect(entries).toEqual([
      { ecosystem: 'cargo', name: 'fixture-app', version: '0.1.0', registry: false, source: 'path (local crate)' },
      { ecosystem: 'cargo', name: 'alpha-crate', version: '1.0.200', registry: true, source: 'crates.io' },
      { ecosystem: 'cargo', name: 'beta-crate', version: '0.3.0', registry: false, source: 'git+https://example.com/beta?rev=abc#abc' },
    ]);
  });

  it('ignores [[patch.unused]] tables', () => {
    const text = cargoLock([{ name: 'a', version: '1.0.0', source: CRATES }]) + '\n[[patch.unused]]\nname = "zzz"\nversion = "9.9.9"\n';
    expect(parseCargoLock(text).map((e) => e.name)).toEqual(['a']);
  });
});

describe('breakingKey', () => {
  it('is the major, or the first non-zero component below 1.0', () => {
    expect(breakingKey('1.4.2')).toBe('1');
    expect(breakingKey('12.0.0-beta.1')).toBe('12');
    expect(breakingKey('0.10.3')).toBe('0.10');
    expect(breakingKey('0.0.7')).toBe('0.0.7');
  });
});

describe('diffEntries', () => {
  it('returns only new or changed versions, with the base versions and whether it is a new major', () => {
    const base = parseNpmLock(
      npmLock({
        'node_modules/same': pkg('same', '1.0.0'),
        'node_modules/patched': pkg('patched', '1.0.0'),
        'node_modules/majored': pkg('majored', '1.9.0'),
        'node_modules/zero': pkg('zero', '0.3.1'),
        'node_modules/gone': pkg('gone', '1.0.0'),
      }),
    );
    const head = parseNpmLock(
      npmLock({
        'node_modules/same': pkg('same', '1.0.0'),
        'node_modules/patched': pkg('patched', '1.0.1'),
        'node_modules/majored': pkg('majored', '2.0.0'),
        'node_modules/zero': pkg('zero', '0.4.0'),
        'node_modules/brand-new': pkg('brand-new', '5.0.0'),
      }),
    );
    const changes = diffEntries(base, head);
    expect(changes.map((c) => [c.name, c.version, c.previous, c.major])).toEqual([
      ['brand-new', '5.0.0', [], false],
      ['majored', '2.0.0', ['1.9.0'], true],
      ['patched', '1.0.1', ['1.0.0'], false],
      ['zero', '0.4.0', ['0.3.1'], true],
    ]);
  });

  it('a second copy at an existing major is not a new major', () => {
    const base = parseNpmLock(npmLock({ 'node_modules/dup': pkg('dup', '2.1.0') }));
    const head = parseNpmLock(
      npmLock({ 'node_modules/dup': pkg('dup', '2.1.0'), 'node_modules/x/node_modules/dup': pkg('dup', '2.3.0') }),
    );
    expect(diffEntries(base, head)).toMatchObject([{ name: 'dup', version: '2.3.0', major: false }]);
  });
});

describe('parseAllowList', () => {
  it('accepts {allow: [...]} with a reason per entry', () => {
    expect(
      parseAllowList(JSON.stringify({ allow: [{ ecosystem: 'npm', name: 'x', version: '1.0.1', reason: ' CVE fix ' }] })),
    ).toEqual([{ ecosystem: 'npm', name: 'x', version: '1.0.1', reason: 'CVE fix' }]);
    expect(parseAllowList('')).toEqual([]);
  });

  it('refuses an entry without a reason or with an unknown ecosystem', () => {
    expect(() => parseAllowList(JSON.stringify({ allow: [{ ecosystem: 'npm', name: 'x', version: '1' }] }))).toThrow(/reason/);
    expect(() => parseAllowList(JSON.stringify({ allow: [{ ecosystem: 'pip', name: 'x', version: '1', reason: 'r' }] }))).toThrow(/ecosystem/);
    expect(() => parseAllowList('{"nope": 1}')).toThrow(/allow/);
  });
});

describe('decideAge', () => {
  it('uses the default embargo, and the longer one for a new major', () => {
    expect(decideAge({ publishedAt: new Date(daysAgo(7.01)), now: NOW, major: false }).ok).toBe(true);
    expect(decideAge({ publishedAt: new Date(daysAgo(6.99)), now: NOW, major: false }).ok).toBe(false);
    expect(decideAge({ publishedAt: new Date(daysAgo(10)), now: NOW, major: true })).toMatchObject({ ok: false, embargoDays: 14 });
    expect(decideAge({ publishedAt: new Date(daysAgo(10)), now: NOW, major: false, days: 3 }).ok).toBe(true);
  });
});

describe('registry URLs', () => {
  it('encodes scoped npm names and crate names', () => {
    expect(npmPackumentUrl('@fixture/beta')).toBe('https://registry.npmjs.org/@fixture%2Fbeta');
    expect(npmPackumentUrl('plain')).toBe('https://registry.npmjs.org/plain');
    expect(cratesVersionUrl('alpha-crate', '1.0.0')).toBe('https://crates.io/api/v1/crates/alpha-crate/1.0.0');
  });
});

describe('mapLimit', () => {
  it('never runs more than the limit at once and keeps result order', async () => {
    let inFlight = 0;
    let peak = 0;
    const res = await mapLimit([1, 2, 3, 4, 5, 6], 2, async (n) => {
      inFlight++;
      peak = Math.max(peak, inFlight);
      await new Promise((r) => setTimeout(r, 1));
      inFlight--;
      if (n === 4) throw new Error('four');
      return n * 10;
    });
    expect(peak).toBe(2);
    expect(res.map((r) => (r.status === 'fulfilled' ? r.value : 'x'))).toEqual([10, 20, 30, 'x', 50, 60]);
  });
});

describe('parseArgs', () => {
  it('requires --base and reads the embargo days', () => {
    expect(parseArgs(['--base', 'abc', '--days', '3', '--major-days', '5'])).toEqual({ base: 'abc', days: 3, majorDays: 5 });
    expect(() => parseArgs([])).toThrow(/--base/);
    expect(() => parseArgs(['--base', 'x', '--days', 'soon'])).toThrow(/days/);
  });
});

// --- the whole check, with a mocked registry ---

type Times = Record<string, Record<string, string>>;
function mockFetch(npm: Times, crates: Times, opts: { failUrls?: RegExp } = {}) {
  const calls: { url: string; ua: string }[] = [];
  const fn = vi.fn(async (input: string | URL | Request, init?: RequestInit) => {
    const url = String(input);
    const ua = String((init?.headers as Record<string, string>)?.['User-Agent'] ?? '');
    calls.push({ url, ua });
    if (opts.failUrls?.test(url)) throw new TypeError('fetch failed');
    const json = (body: unknown, status = 200) => new Response(JSON.stringify(body), { status });
    if (url.startsWith(REG)) {
      const name = decodeURIComponent(url.slice(REG.length));
      return npm[name] ? json({ name, time: npm[name] }) : json({ error: 'Not found' }, 404);
    }
    const m = /crates\/([^/]+)\/([^/]+)$/.exec(url);
    if (m) {
      const t = crates[decodeURIComponent(m[1]!)]?.[decodeURIComponent(m[2]!)];
      return t ? json({ version: { num: m[2], created_at: t } }) : json({ errors: [] }, 404);
    }
    return json({}, 500);
  });
  return { fn: fn as unknown as typeof fetch, calls };
}

const baseNpm = npmLock({ 'node_modules/old-lib': pkg('old-lib', '1.0.0'), 'node_modules/major-lib': pkg('major-lib', '1.0.0') });
const baseCargo = cargoLock([{ name: 'fixture-app', version: '0.1.0' }, { name: 'old-crate', version: '1.0.0', source: CRATES }]);

describe('checkReleaseAge', () => {
  it('passes when every new version is past its embargo, and checks nothing that did not change', async () => {
    const head = {
      npm: npmLock({ 'node_modules/old-lib': pkg('old-lib', '1.0.1'), 'node_modules/major-lib': pkg('major-lib', '2.0.0') }),
      cargo: cargoLock([{ name: 'fixture-app', version: '0.1.0' }, { name: 'old-crate', version: '1.0.0', source: CRATES }]),
    };
    const { fn, calls } = mockFetch({ 'old-lib': { '1.0.1': daysAgo(8) }, 'major-lib': { '2.0.0': daysAgo(15) } }, {});
    const r = await checkReleaseAge({ base: { npm: baseNpm, cargo: baseCargo }, head, allow: '', now: NOW, fetchImpl: fn });
    expect(r.code).toBe(0);
    expect(calls.map((c) => c.url).sort()).toEqual([`${REG}major-lib`, `${REG}old-lib`]);
    expect(r.lines.join('\n')).toMatch(/ok\s+npm major-lib 1\.0\.0 -> 2\.0\.0 .*embargo 14d \(new major\)/);
  });

  it('fails a version younger than the embargo, and a new major younger than 14 days', async () => {
    const head = {
      npm: npmLock({ 'node_modules/old-lib': pkg('old-lib', '1.0.1'), 'node_modules/major-lib': pkg('major-lib', '2.0.0') }),
      cargo: cargoLock([{ name: 'fixture-app', version: '0.1.0' }, { name: 'old-crate', version: '1.1.0', source: CRATES }]),
    };
    const { fn, calls } = mockFetch(
      { 'old-lib': { '1.0.1': daysAgo(2) }, 'major-lib': { '2.0.0': daysAgo(10) } },
      { 'old-crate': { '1.1.0': daysAgo(1) } },
    );
    const r = await checkReleaseAge({ base: { npm: baseNpm, cargo: baseCargo }, head, allow: '', now: NOW, fetchImpl: fn });
    expect(r.code).toBe(1);
    const out = r.lines.join('\n');
    expect(out).toMatch(/EMBARGOED\s+npm old-lib 1\.0\.0 -> 1\.0\.1/);
    expect(out).toMatch(/EMBARGOED\s+npm major-lib 1\.0\.0 -> 2\.0\.0 .*new major/);
    expect(out).toMatch(/EMBARGOED\s+cargo old-crate 1\.0\.0 -> 1\.1\.0/);
    expect(out).toContain('.dependency-embargo-allow.json');
    // crates.io requires a descriptive User-Agent.
    expect(calls.find((c) => c.url.includes('crates.io'))?.ua).toMatch(/albedo/);
  });

  it('lets an allow-listed version through with its reason', async () => {
    const head = { npm: npmLock({ 'node_modules/old-lib': pkg('old-lib', '1.0.1'), 'node_modules/major-lib': pkg('major-lib', '1.0.0') }), cargo: baseCargo };
    const { fn } = mockFetch({ 'old-lib': { '1.0.1': daysAgo(1) } }, {});
    const allow = JSON.stringify({ allow: [{ ecosystem: 'npm', name: 'old-lib', version: '1.0.1', reason: 'security fix for an advisory' }] });
    const r = await checkReleaseAge({ base: { npm: baseNpm, cargo: baseCargo }, head, allow, now: NOW, fetchImpl: fn });
    expect(r.code).toBe(0);
    expect(r.lines.join('\n')).toMatch(/ALLOWED\s+npm old-lib .*security fix for an advisory/);
  });

  it('an allow entry for another version does not apply', async () => {
    const head = { npm: npmLock({ 'node_modules/old-lib': pkg('old-lib', '1.0.2'), 'node_modules/major-lib': pkg('major-lib', '1.0.0') }), cargo: baseCargo };
    const { fn } = mockFetch({ 'old-lib': { '1.0.2': daysAgo(1) } }, {});
    const allow = JSON.stringify({ allow: [{ ecosystem: 'npm', name: 'old-lib', version: '1.0.1', reason: 'r' }] });
    const r = await checkReleaseAge({ base: { npm: baseNpm, cargo: baseCargo }, head, allow, now: NOW, fetchImpl: fn });
    expect(r.code).toBe(1);
  });

  it('fails closed when the registry cannot be reached or has no publish time', async () => {
    const head = {
      npm: npmLock({ 'node_modules/old-lib': pkg('old-lib', '1.0.1'), 'node_modules/major-lib': pkg('major-lib', '1.0.0') }),
      cargo: cargoLock([{ name: 'fixture-app', version: '0.1.0' }, { name: 'old-crate', version: '1.0.1', source: CRATES }]),
    };
    const { fn } = mockFetch({ 'old-lib': { '9.9.9': daysAgo(100) } }, {}, { failUrls: /crates\.io/ });
    const r = await checkReleaseAge({ base: { npm: baseNpm, cargo: baseCargo }, head, allow: '', now: NOW, fetchImpl: fn });
    expect(r.code).toBe(2);
    const out = r.lines.join('\n');
    expect(out).toMatch(/UNVERIFIED\s+npm old-lib .*no publish time/);
    expect(out).toMatch(/UNVERIFIED\s+cargo old-crate .*fetch failed/);
    expect(out).toMatch(/fails closed/);
  });

  it('lists git, file and local-path changes as skipped without asking a registry', async () => {
    const head = {
      npm: npmLock({
        'node_modules/old-lib': pkg('old-lib', '1.0.0'),
        'node_modules/major-lib': pkg('major-lib', '1.0.0'),
        'node_modules/from-git': { version: '1.0.0', resolved: 'git+https://example.com/x.git#abc' },
      }),
      cargo: cargoLock([{ name: 'fixture-app', version: '0.2.0' }, { name: 'old-crate', version: '1.0.0', source: CRATES }]),
    };
    const { fn, calls } = mockFetch({}, {});
    const r = await checkReleaseAge({ base: { npm: baseNpm, cargo: baseCargo }, head, allow: '', now: NOW, fetchImpl: fn });
    expect(r.code).toBe(0);
    expect(calls).toEqual([]);
    const out = r.lines.join('\n');
    expect(out).toMatch(/Skipped/);
    expect(out).toMatch(/npm from-git \(new\) 1\.0\.0\s+\[git\+https/);
    expect(out).toMatch(/cargo fixture-app 0\.1\.0 -> 0\.2\.0\s+\[path \(local crate\)\]/);
  });

  it('fetches an npm packument once for several versions of one package', async () => {
    const head = {
      npm: npmLock({
        'node_modules/old-lib': pkg('old-lib', '1.0.0'),
        'node_modules/major-lib': pkg('major-lib', '1.0.0'),
        'node_modules/multi': pkg('multi', '3.0.0'),
        'node_modules/a/node_modules/multi': pkg('multi', '2.0.0'),
      }),
      cargo: baseCargo,
    };
    const { fn, calls } = mockFetch({ multi: { '2.0.0': daysAgo(30), '3.0.0': daysAgo(30) } }, {});
    const r = await checkReleaseAge({ base: { npm: baseNpm, cargo: baseCargo }, head, allow: '', now: NOW, fetchImpl: fn });
    expect(r.code).toBe(0);
    expect(calls).toHaveLength(1);
  });
});
